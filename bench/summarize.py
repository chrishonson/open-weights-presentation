"""Combine measured results into benchmarks.json (canonical) and benchmarks.js (loaded by index.html).

Usage: python3 bench/summarize.py
Every speed, memory and accuracy number comes from bench/results/*.json. Nothing is typed in by hand.
"""
import json
import pathlib
import re
from collections import Counter
from decimal import ROUND_HALF_UP, Decimal

from ollama_client import get, post

HERE = pathlib.Path(__file__).parent
ROOT = HERE.parent
GB = 1e9


# Where the deck's numbers come from. Speed and document reads: the first file that has the model, all measured on
# Ollama 0.40.6 with the same text for every model. Peak memory for llama.cpp models measured before the probe fix
# comes from the memory rerun. Accuracy: the challenge set only.
SPEED_SOURCES = ["night2-speed.json", "night1-speed.json"]
MEMORY_SOURCE = "night1-memory.json"
ACCURACY_SOURCE = "challenge.json"
# Ollama's two engines, named as the deck names them.
ENGINES = {"MLX": "newer", "llama.cpp": "older"}


def load(name):
    p = HERE / "results" / name
    return json.loads(p.read_text()) if p.exists() else {"models": {}}


def model_facts(tag):
    show = post("/api/show", {"model": tag})
    info = show.get("model_info", {})
    ctx = next((v for k, v in info.items() if k.endswith(".context_length")), None)
    disk = next(m["size"] for m in get("/api/tags")["models"] if m["name"] == tag)
    return {
        "params_b": round(info.get("general.parameter_count", 0) / GB, 1),
        "quantization": show["details"].get("quantization_level") or show.get("quantization"),
        "max_context_tokens": ctx,
        "download_gb": round(disk / GB, 1),
    }


def main():
    meta = json.loads((HERE / "models.json").read_text())
    speeds, memory, quiz = [load(f) for f in SPEED_SOURCES], load(MEMORY_SOURCE), load(ACCURACY_SOURCE)
    speed = speeds[0]
    models = []
    for tag, m in meta.items():
        s = next((src["models"][tag] for src in speeds if tag in src["models"]), {})
        contexts = {k: dict(c) for k, c in s.get("contexts", {}).items()}
        for k, c in contexts.items():
            if c.get("memory_gb") is None and not c.get("crashed"):
                c["memory_gb"] = memory["models"].get(tag, {}).get("contexts", {}).get(k, {}).get("memory_gb")
        s = {**s, "contexts": contexts}
        entry = {"tag": tag, **m, **model_facts(tag)}
        entry["speed"] = {
            "load_seconds": s.get("load_seconds"),
            "tokens_per_second": s.get("gen_tok_s"),
            "tokens_per_second_runs": s.get("gen_tok_s_runs"),
        }
        entry["by_context"] = s.get("contexts", {})
        entry["memory_gb_idle"] = s.get("memory_gb_idle")
        entry["ollama_version"] = s.get("ollama_version") or quiz["models"].get(tag, {}).get("ollama_version")
        if tag in quiz["models"]:
            entry["quiz"] = quiz["models"][tag]["summary"]
        models.append(entry)

    # Most models share one Ollama version. Any model measured on another one is labelled wherever its numbers appear.
    ollama_version = Counter(m["ollama_version"] for m in models).most_common(1)[0][0]
    out = {
        # GPU limit is Metal's recommendedMaxWorkingSetSize on this machine: 51.84 GiB = 55.7 GB.
        # Apple's "64 GB" of memory is 64 GiB. Every size in the deck is decimal GB, so the memory is restated in GB.
        "machine": {**speed.get("environment", {}), "ollama_version": ollama_version, "gpu_memory_limit_gb": 55.7,
                    "memory_gb": round(int(speed["environment"]["memory"].split()[0]) * 2**30 / GB, 1), "memory_bandwidth_gb_s_apple_spec": 400},
        "method": {
            "speed": "Ollama API timings. Median of 3 runs, 300-token reply, temperature 0. Documents are the same Python source code for every model, so token counts differ by tokenizer.",
            "memory": "Peak memory of the model's runner process while it reads a document of the given size, in a runner freshly loaded for that document: the larger of macOS footprint and resident size, sampled every 0.5 s, and the kernel's footprint peak, reset after loading.",
            "quiz": "Challenge set: 29 questions chosen to separate models (14 math, 3 logic, 12 Python coding tasks graded by unit tests). 15 come from an earlier 80-question quiz, the rest are new; questions every model answered correctly are not asked. Thinking off unless the model cannot turn it off. Max 6,144 tokens per answer.",
            "quiz_settings": quiz.get("settings"),
            "quiz_questions": len(next(iter(quiz["models"].values()))["questions"]),
        },
        "models": models,
        "voice": load_voice(),
    }
    (ROOT / "benchmarks.json").write_text(json.dumps(out, indent=2) + "\n")
    (ROOT / "benchmarks.js").write_text("// Generated by bench/summarize.py from bench/results. Do not edit by hand.\nwindow.BENCHMARKS = " + json.dumps(out, indent=2) + ";\n")
    memory_md, speed_md = markdown_tables(models)
    (HERE / "results" / "tables.md").write_text(f"## Memory and waiting time\n\n{memory_md}\n\n## Speed and accuracy\n\n{speed_md}\n")
    fill(ROOT / "README.md", "tables", f"### Memory and waiting time\n\n{memory_md}\n\n### Speed and accuracy\n\n{speed_md}")
    print(f"Wrote benchmarks.json, benchmarks.js and bench/results/tables.md for {len(models)} models")


def load_voice():
    """The voice loop session named in voice.json: its settings plus voice_summary of its turns."""
    meta = json.loads((HERE / "voice.json").read_text())
    rows = [json.loads(l) for l in (HERE / "results" / meta["file"]).read_text().splitlines() if l.strip()]
    return {**meta, **voice_summary(rows)}


def voice_summary(rows):
    """Voice to voice: from the end of speech to the first reply audio. The median turn is split into its stages."""
    turns = sorted((r for r in rows if r.get("voice_to_voice_ms") is not None), key=lambda r: r["voice_to_voice_ms"])
    mid = turns[len(turns) // 2]
    stages = {k: mid[k] for k in ("hangover_ms", "stt_ms", "llm_ms", "tts_ms")}
    stages["other_ms"] = mid["voice_to_voice_ms"] - sum(stages.values())  # end-of-speech detection lag and queueing
    return {"turns": len(turns), "min_ms": turns[0]["voice_to_voice_ms"], "median_ms": mid["voice_to_voice_ms"],
            "max_ms": turns[-1]["voice_to_voice_ms"], "median_turn_stages_ms": stages}


def num(v, d):
    """Round half up, like the deck's JavaScript toFixed, so every output shows the same digits."""
    return str(Decimal(str(v)).quantize(Decimal(1).scaleb(-d), rounding=ROUND_HALF_UP))


def k_tokens(n):
    """Token count in decimal thousands, like the deck's kTokens: 1,838 -> 1.8K, 131,072 -> 131K."""
    return f"{num(n / 1000, 0 if n >= 10000 else 1)}K"


def fmt(v, d=1, suffix=""):
    return "–" if v is None else f"{num(v, d)}{suffix}"


def wait(s):
    if s is None:
        return "–"
    return f"{num(s, 0)} s" if s < 60 else f"{num(s / 60, 1)} min" if s < 3600 else f"{num(s / 3600, 1)} hours"


def plural(n, word):
    return f"{n} {word}" if n == 1 else f"{n} {word}s"


def counted_wrong(n):
    return "which counts as wrong" if n == 1 else "which count as wrong"


def markdown_tables(models):
    mem_keys = wait_keys = sorted({k for m in models for k in m["by_context"]}, key=int)
    head = "| Model | Engine | Format | Download | Context window | " + " | ".join(f"Memory @ {k_tokens(int(k))}" for k in mem_keys) + " | " + " | ".join(f"Wait @ {k_tokens(int(k))}" for k in wait_keys) + " |"
    rows = [head, "| :--- | :--- | :--- | ---: | ---: | " + " | ".join(["---:"] * (len(mem_keys) + len(wait_keys))) + " |"]
    def cell(m, k, value):
        c = m["by_context"].get(k)
        # The bucket is named for its context size, but a document read whole fits even when the window is smaller.
        read_whole = c and c.get("prompt_tokens") and not c.get("truncated")
        if int(k) > (m["max_context_tokens"] or 0) and not read_whole:
            return "over max"
        if c and c.get("crashed"):
            return "crashes"
        return value(c or {})

    for m in models:
        rows.append(f"| {m['name']} | {ENGINES.get(m.get('runner'), m.get('runner') or '–')} | {m.get('quantization') or '–'} | {m['download_gb']} GB | {k_tokens(m['max_context_tokens'])} tokens | "
                    + " | ".join(cell(m, k, lambda c: fmt(c.get("memory_gb"), 1, " GB")) for k in mem_keys) + " | "
                    + " | ".join(cell(m, k, lambda c: wait(c.get("wait_before_first_token_s"))) for k in wait_keys) + " |")
    memory = "\n".join(rows)

    rows = ["| Model | Writing speed (tokens/sec) | Challenge (29) | Math (14) | Coding (12) | Avg. time per answer |",
            "| :--- | ---: | ---: | ---: | ---: | ---: |"]
    for m in sorted(models, key=lambda m: -(m.get("quiz", {}).get("overall_pct") or -1)):
        q = m.get("quiz", {})
        rows.append(f"| {m['name']} | {fmt(m['speed']['tokens_per_second'], 0)} | {fmt(q.get('overall_pct'), 0, '%')} | "
                    f"{fmt(q.get('math_pct'), 0, '%')} | {fmt(q.get('coding_pct'), 0, '%')} | {wait(q.get('avg_seconds_per_question'))} |")
    notes = []
    main_version = Counter(m.get("ollama_version") for m in models).most_common(1)[0][0]
    for m in models:
        if m.get("ollama_version") != main_version:
            notes.append(f"{m['name']} was measured on Ollama {m['ollama_version']}, the others on {main_version}.")
        q = m.get("quiz", {})
        if q.get("crashed"):
            notes.append(f"{m['name']} crashed on {plural(q['crashed'], 'question')}, {counted_wrong(q['crashed'])}.")
        if q.get("hit_token_limit"):
            notes.append(f"{m['name']} ran out of room on {plural(q['hit_token_limit'], 'answer')}, {counted_wrong(q['hit_token_limit'])}.")
    return memory, "\n".join(rows) + ("\n\n" + " ".join(notes) if notes else "")


def fill(path, name, content):
    """Replace the text between <!-- name:start --> and <!-- name:end --> in a Markdown file."""
    text = path.read_text()
    pattern = re.compile(rf"(<!-- {name}:start -->\n).*?(<!-- {name}:end -->)", re.S)
    path.write_text(pattern.sub(lambda m: m.group(1) + content + "\n" + m.group(2), text))


if __name__ == "__main__":
    main()
    from publish_openrouter import main as publish_hosted
    publish_hosted()
